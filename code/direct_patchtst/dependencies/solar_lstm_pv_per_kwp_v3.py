def final_physical_postprocess(
    pred_per_kwp: np.ndarray,
    daylight: np.ndarray,
    clip_per_kwp: bool,
    max_kw_per_kwp: float,
    force_night_zero: bool,
) -> np.ndarray:
    """Apply the same physical output constraints used in evaluation."""
    pred = np.asarray(pred_per_kwp, dtype=np.float32).copy()
    day = np.asarray(daylight, dtype=np.float32)
    if force_night_zero:
        pred = np.where(day > 0.5, pred, 0.0)
    if clip_per_kwp:
        pred = np.clip(pred, 0.0, float(max_kw_per_kwp))
    return pred.astype(np.float32)


def fit_bias_correction_params(
    pred_per_kwp: np.ndarray,
    true_per_kwp: np.ndarray,
    daylight: np.ndarray,
    method: str,
) -> Dict[str, object]:
    """
    Fit a tiny calibration layer on validation predictions only.

    Convention:
      error = pred - true
      corrected = pred - fitted_error

    This is intentionally simple and transparent. It is not a second model.
    """
    method = str(method).lower().strip()
    pred = np.asarray(pred_per_kwp, dtype=np.float64)
    true = np.asarray(true_per_kwp, dtype=np.float64)
    day = np.asarray(daylight, dtype=np.float64) > 0.5
    err = pred - true

    if method == "none":
        return {"method": "none"}

    if method == "global_bias":
        return {
            "method": method,
            "global_bias": float(np.nanmean(err)),
        }

    if method == "daylight_bias":
        global_bias = float(np.nanmean(err))
        day_bias = float(np.nanmean(err[day])) if np.any(day) else global_bias
        night_bias = float(np.nanmean(err[~day])) if np.any(~day) else global_bias
        return {
            "method": method,
            "global_bias": global_bias,
            "daylight_bias": day_bias,
            "night_bias": night_bias,
        }

    if method == "horizon_bias":
        h_bias = np.nanmean(err, axis=0).astype(float)
        return {
            "method": method,
            "horizon_bias": h_bias.tolist(),
            "global_bias": float(np.nanmean(err)),
        }

    if method == "horizon_daylight_bias":
        horizon = err.shape[1]
        global_bias = float(np.nanmean(err))
        h_day = np.zeros(horizon, dtype=float)
        h_night = np.zeros(horizon, dtype=float)
        h_all = np.nanmean(err, axis=0).astype(float)
        for h in range(horizon):
            m_day = day[:, h]
            m_night = ~m_day
            h_day[h] = float(np.nanmean(err[m_day, h])) if np.any(m_day) else float(h_all[h])
            h_night[h] = float(np.nanmean(err[m_night, h])) if np.any(m_night) else float(h_all[h])
        return {
            "method": method,
            "global_bias": global_bias,
            "horizon_bias": h_all.tolist(),
            "horizon_daylight_bias": h_day.tolist(),
            "horizon_night_bias": h_night.tolist(),
        }

    if method == "linear":
        x = pred.reshape(-1)
        y = true.reshape(-1)
        mask = np.isfinite(x) & np.isfinite(y)
        if mask.sum() < 2 or float(np.var(x[mask])) <= 1e-12:
            slope, intercept = 1.0, -float(np.nanmean(err))
        else:
            slope, intercept = np.polyfit(x[mask], y[mask], deg=1)
            slope = float(np.clip(slope, 0.50, 1.50))
            intercept = float(intercept)
        return {
            "method": method,
            "linear_slope": slope,
            "linear_intercept": intercept,
        }

    raise ValueError(
        f"Unknown bias correction method: {method}. "
        "Allowed: none, global_bias, daylight_bias, horizon_bias, horizon_daylight_bias, linear"
    )


def apply_bias_correction(
    pred_per_kwp: np.ndarray,
    daylight: np.ndarray,
    params: Dict[str, object],
) -> np.ndarray:
    method = str(params.get("method", "none")).lower().strip()
    pred = np.asarray(pred_per_kwp, dtype=np.float64).copy()
    day = np.asarray(daylight, dtype=np.float64) > 0.5

    if method == "none":
        return pred.astype(np.float32)

    if method == "global_bias":
        return (pred - float(params["global_bias"])).astype(np.float32)

    if method == "daylight_bias":
        corrected = pred.copy()
        corrected[day] -= float(params["daylight_bias"])
        corrected[~day] -= float(params["night_bias"])
        return corrected.astype(np.float32)

    if method == "horizon_bias":
        h_bias = np.asarray(params["horizon_bias"], dtype=np.float64).reshape(1, -1)
        return (pred - h_bias).astype(np.float32)

    if method == "horizon_daylight_bias":
        h_day = np.asarray(params["horizon_daylight_bias"], dtype=np.float64).reshape(1, -1)
        h_night = np.asarray(params["horizon_night_bias"], dtype=np.float64).reshape(1, -1)
        bias = np.where(day, h_day, h_night)
        return (pred - bias).astype(np.float32)

    if method == "linear":
        slope = float(params["linear_slope"])
        intercept = float(params["linear_intercept"])
        return (slope * pred + intercept).astype(np.float32)

    raise ValueError(f"Unknown correction method in params: {method}")


def get_metric_for_selection(metrics: Dict[str, float], metric_name: str) -> float:
    metric_name = str(metric_name)
    if metric_name == "abs_bias_pct_of_reference_capacity":
        return abs(float(metrics.get("bias_pct_of_reference_capacity", float("inf"))))
    if metric_name not in metrics:
        raise ValueError(f"Calibration metric not available: {metric_name}")
    return float(metrics[metric_name])


def choose_validation_correction(
    val_pred: np.ndarray,
    val_true: np.ndarray,
    val_daylight: np.ndarray,
    correction_methods: Sequence[str],
    selection_metric: str,
    reference_capacity_kwp: float,
    clip_per_kwp: bool,
    max_kw_per_kwp: float,
    force_night_zero: bool,
) -> Tuple[Dict[str, object], pd.DataFrame]:
    rows = []
    best_params: Optional[Dict[str, object]] = None
    best_score = float("inf")

    for method in correction_methods:
        params = fit_bias_correction_params(val_pred, val_true, val_daylight, method)
        corrected = apply_bias_correction(val_pred, val_daylight, params)
        corrected = final_physical_postprocess(
            corrected,
            val_daylight,
            clip_per_kwp=clip_per_kwp,
            max_kw_per_kwp=max_kw_per_kwp,
            force_night_zero=force_night_zero,
        )
        metrics = compute_all_metrics(corrected, val_true, val_daylight, reference_capacity_kwp)
        score = get_metric_for_selection(metrics, selection_metric)
        row = {
            "correction_method": method,
            "selection_metric": selection_metric,
            "selection_score": score,
            **{f"val_{k}": v for k, v in metrics.items()},
        }
        # Keep common scalar correction parameters readable in CSV.
        for key in ["global_bias", "daylight_bias", "night_bias", "linear_slope", "linear_intercept"]:
            if key in params:
                row[key] = params[key]
        rows.append(row)
        if score < best_score:
            best_score = score
            best_params = params

    if best_params is None:
        best_params = {"method": "none"}

    return best_params, pd.DataFrame(rows).sort_values("selection_score").reset_index(drop=True)


def per_horizon_metrics(
    pred_per_kwp: np.ndarray,
    true_per_kwp: np.ndarray,
    daylight: np.ndarray,
    reference_capacity_kwp: float,
) -> pd.DataFrame:
    rows = []
    for h in range(pred_per_kwp.shape[1]):
        metrics = compute_all_metrics(
            pred_per_kwp[:, h:h + 1],
            true_per_kwp[:, h:h + 1],
            daylight[:, h:h + 1],
            reference_capacity_kwp,
        )
        rows.append({"horizon_step": h + 1, **metrics})
    return pd.DataFrame(rows)


