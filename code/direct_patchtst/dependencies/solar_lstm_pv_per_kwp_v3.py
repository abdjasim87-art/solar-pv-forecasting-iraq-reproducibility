def train_one_seed(
    train_loader: DataLoader,
    val_loader: DataLoader,
    test_loader: DataLoader,
    n_features: int,
    n_cities: int,
    y_scaler: StandardScaler,
    args,
    device: str,
    seed: int,
    embedding_dim: Optional[int],
    checkpoint_path: Optional[str],
):
    set_seed(seed)
    use_city_embedding = args.mode == "city_embedding"

    if use_city_embedding:
        model = SolarLSTMCityEmbedding(
            n_features=n_features,
            n_cities=n_cities,
            city_embedding_dim=int(embedding_dim),
            hidden_size=args.hidden_size,
            num_layers=args.num_layers,
            dropout=args.dropout,
            horizon=args.horizon,
            head_hidden=args.head_hidden,
        ).to(device)
    else:
        model = SolarLSTM(
            n_features=n_features,
            hidden_size=args.hidden_size,
            num_layers=args.num_layers,
            dropout=args.dropout,
            horizon=args.horizon,
            head_hidden=args.head_hidden,
        ).to(device)

    n_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    print(f"  Model parameters: {n_params:,}")

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.lr,
        weight_decay=args.weight_decay,
    )

    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer,
        mode="min",
        factor=args.lr_factor,
        patience=args.lr_patience,
    )

    horizon_weights = build_horizon_weights(args.horizon, device)
    early = EarlyStopping(patience=args.early_patience, min_delta=args.min_delta)

    best_state = None
    best_epoch = 0
    best_val_metric = float("inf")

    for epoch in range(1, args.epochs + 1):
        train_loss = train_one_epoch(
            model=model,
            loader=train_loader,
            optimizer=optimizer,
            horizon_weights=horizon_weights,
            device=device,
            use_city_embedding=use_city_embedding,
            grad_clip=args.grad_clip,
            loss_name=args.loss,
            huber_beta=args.huber_beta,
            daylight_weight=args.active_daylight_weight,
            night_weight=args.night_weight,
            production_weight=args.active_production_weight,
            max_kw_per_kwp=args.max_kw_per_kwp,
        )

        val_metrics, _ = evaluate_model(
            model=model,
            loader=val_loader,
            y_scaler=y_scaler,
            device=device,
            use_city_embedding=use_city_embedding,
            reference_capacity_kwp=args.reference_capacity_kwp,
            clip_per_kwp=args.clip_per_kwp,
            max_kw_per_kwp=args.max_kw_per_kwp,
            force_night_zero=args.force_night_zero,
        )

        if args.monitor_metric not in val_metrics:
            raise ValueError(f"Monitor metric not available: {args.monitor_metric}")
        monitor_metric = val_metrics[args.monitor_metric]
        scheduler.step(monitor_metric)
        stop, improved = early.step(monitor_metric)

        if improved:
            best_state = copy.deepcopy(model.state_dict())
            best_epoch = epoch
            best_val_metric = monitor_metric

        if args.verbose:
            print(
                f"  epoch={epoch:03d} | train_loss={train_loss:.6f} | "
                f"val_per_kwp_RMSE={val_metrics['per_kwp_rmse']:.6f} | "
                f"val_daylight_RMSE={val_metrics.get('daylight_per_kwp_rmse', float('nan')):.6f} | "
                f"val_ref_RMSE={val_metrics['reference_kw_rmse']:.2f} kW | "
                f"val_R2={val_metrics['per_kwp_r2']:.4f}"
            )

        if stop:
            print(f"  Early stop at epoch {epoch}.")
            break

    if best_state is None:
        best_state = copy.deepcopy(model.state_dict())

    model.load_state_dict(best_state)

    if checkpoint_path is not None:
        torch.save(best_state, checkpoint_path)

    # v3: fit transparent post-processing correction on validation only,
    # then apply the selected correction to test.
    val_pred, val_true, val_daylight = collect_predictions(
        model=model,
        loader=val_loader,
        y_scaler=y_scaler,
        device=device,
        use_city_embedding=use_city_embedding,
        clip_per_kwp=args.clip_per_kwp,
        max_kw_per_kwp=args.max_kw_per_kwp,
        force_night_zero=args.force_night_zero,
    )
    test_pred, test_true, test_daylight = collect_predictions(
        model=model,
        loader=test_loader,
        y_scaler=y_scaler,
        device=device,
        use_city_embedding=use_city_embedding,
        clip_per_kwp=args.clip_per_kwp,
        max_kw_per_kwp=args.max_kw_per_kwp,
        force_night_zero=args.force_night_zero,
    )

    correction_params, calibration_df = choose_validation_correction(
        val_pred=val_pred,
        val_true=val_true,
        val_daylight=val_daylight,
        correction_methods=args.bias_corrections,
        selection_metric=args.calibration_metric,
        reference_capacity_kwp=args.reference_capacity_kwp,
        clip_per_kwp=args.clip_per_kwp,
        max_kw_per_kwp=args.max_kw_per_kwp,
        force_night_zero=args.force_night_zero,
    )

    corrected_test_pred = apply_bias_correction(test_pred, test_daylight, correction_params)
    corrected_test_pred = final_physical_postprocess(
        corrected_test_pred,
        test_daylight,
        clip_per_kwp=args.clip_per_kwp,
        max_kw_per_kwp=args.max_kw_per_kwp,
        force_night_zero=args.force_night_zero,
    )

    test_metrics = compute_all_metrics(
        corrected_test_pred,
        test_true,
        test_daylight,
        args.reference_capacity_kwp,
    )
    per_horizon = per_horizon_metrics(
        corrected_test_pred,
        test_true,
        test_daylight,
        args.reference_capacity_kwp,
    )

    correction_method = str(correction_params.get("method", "none"))
    test_metrics["selected_correction_method"] = correction_method
    test_metrics["selected_correction_selection_metric"] = args.calibration_metric
    test_metrics["selected_correction_val_score"] = float(calibration_df.iloc[0]["selection_score"]) if len(calibration_df) else float("nan")

    return test_metrics, per_horizon, best_epoch, best_val_metric, calibration_df, correction_params


