def build_horizon_weights(horizon: int, device: str) -> torch.Tensor:
    weights = torch.linspace(1.0, 1.5, horizon, device=device)
    return weights / weights.mean()


def elementwise_base_loss(pred: torch.Tensor, true: torch.Tensor, loss_name: str, huber_beta: float) -> torch.Tensor:
    loss_name = loss_name.lower()
    if loss_name == "mse":
        return (pred - true) ** 2
    if loss_name == "mae":
        return torch.abs(pred - true)
    if loss_name == "huber":
        diff = torch.abs(pred - true)
        beta = float(huber_beta)
        return torch.where(diff < beta, 0.5 * diff ** 2 / beta, diff - 0.5 * beta)
    raise ValueError("loss must be mse, mae, or huber")


def solar_weighted_loss(
    pred_scaled: torch.Tensor,
    true_scaled: torch.Tensor,
    true_raw: torch.Tensor,
    daylight: torch.Tensor,
    horizon_weights: torch.Tensor,
    loss_name: str,
    huber_beta: float,
    daylight_weight: float,
    night_weight: float,
    production_weight: float,
    max_kw_per_kwp: float,
) -> torch.Tensor:
    """
    Daylight-focused weighted loss.

    v2 change from v1:
    - daylight hours get an explicit weight;
    - night hours can be down-weighted so night zeros do not dominate;
    - higher-production hours get extra weight;
    - horizon weights are kept;
    - the final loss is normalized by the sum of weights so the scale remains stable
      when trying different daylight/production weights.
    """
    base = elementwise_base_loss(pred_scaled, true_scaled, loss_name, huber_beta)

    day = (daylight > 0.5).float()
    day_w = day * float(daylight_weight) + (1.0 - day) * float(night_weight)

    denom = max(float(max_kw_per_kwp), 1e-6)
    prod = torch.clamp(true_raw / denom, min=0.0, max=1.5)
    prod_w = 1.0 + float(production_weight) * prod

    h_w = horizon_weights.unsqueeze(0)
    weights = day_w * prod_w * h_w

    weighted = base * weights
    return weighted.sum() / torch.clamp(weights.sum(), min=1.0)


def inverse_scaled(arr: np.ndarray, scaler: StandardScaler) -> np.ndarray:
    shape = arr.shape
    inv = scaler.inverse_transform(arr.reshape(-1, 1))
    return inv.reshape(shape)


def compute_regression_metrics(pred: np.ndarray, true: np.ndarray, prefix: str = "") -> Dict[str, float]:
    pred_flat = pred.reshape(-1).astype(float)
    true_flat = true.reshape(-1).astype(float)
    diff = pred_flat - true_flat

    mae = float(np.mean(np.abs(diff)))
    rmse = float(np.sqrt(np.mean(diff ** 2)))
    denom = float(np.sum((true_flat - np.mean(true_flat)) ** 2))
    r2 = float("nan") if denom <= 0 else float(1.0 - np.sum(diff ** 2) / denom)

    return {
        f"{prefix}mae": mae,
        f"{prefix}rmse": rmse,
        f"{prefix}r2": r2,
        f"{prefix}bias": float(np.mean(diff)),
        f"{prefix}mean_true": float(np.mean(true_flat)),
        f"{prefix}mean_pred": float(np.mean(pred_flat)),
        f"{prefix}count": int(pred_flat.size),
    }


def compute_all_metrics(
    pred_per_kwp: np.ndarray,
    true_per_kwp: np.ndarray,
    daylight: Optional[np.ndarray],
    reference_capacity_kwp: float,
) -> Dict[str, float]:
    out: Dict[str, float] = {}

    out.update(compute_regression_metrics(pred_per_kwp, true_per_kwp, prefix="per_kwp_"))

    pred_ref_kw = pred_per_kwp * float(reference_capacity_kwp)
    true_ref_kw = true_per_kwp * float(reference_capacity_kwp)
    out.update(compute_regression_metrics(pred_ref_kw, true_ref_kw, prefix="reference_kw_"))

    # Percent-of-reference-capacity metrics. Since target is kW/kWp, this is numerically percent of capacity.
    diff_per_kwp = (pred_per_kwp.reshape(-1) - true_per_kwp.reshape(-1)).astype(float)
    out["mae_pct_of_reference_capacity"] = float(np.mean(np.abs(diff_per_kwp)) * 100.0)
    out["rmse_pct_of_reference_capacity"] = float(np.sqrt(np.mean(diff_per_kwp ** 2)) * 100.0)
    out["bias_pct_of_reference_capacity"] = float(np.mean(diff_per_kwp) * 100.0)

    out["mean_true_capacity_factor_pct"] = float(np.mean(true_per_kwp.reshape(-1)) * 100.0)
    out["mean_pred_capacity_factor_pct"] = float(np.mean(pred_per_kwp.reshape(-1)) * 100.0)

    if daylight is not None:
        mask = daylight.reshape(-1).astype(bool)
        if mask.any():
            out.update(
                compute_regression_metrics(
                    pred_per_kwp.reshape(-1)[mask],
                    true_per_kwp.reshape(-1)[mask],
                    prefix="daylight_per_kwp_",
                )
            )
            day_diff = diff_per_kwp[mask]
            out["daylight_rmse_pct_of_reference_capacity"] = float(np.sqrt(np.mean(day_diff ** 2)) * 100.0)
            out["daylight_mae_pct_of_reference_capacity"] = float(np.mean(np.abs(day_diff)) * 100.0)

    return out


