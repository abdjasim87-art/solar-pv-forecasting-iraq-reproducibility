def fit_apply_scalers(
    train_df: pd.DataFrame,
    val_df: pd.DataFrame,
    test_df: pd.DataFrame,
    feature_cols: Sequence[str],
    continuous_cols: Sequence[str],
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, Optional[StandardScaler], StandardScaler]:
    train_df = train_df.copy()
    val_df = val_df.copy()
    test_df = test_df.copy()

    x_scaler = None
    if continuous_cols:
        x_scaler = StandardScaler()
        train_df[list(continuous_cols)] = x_scaler.fit_transform(
            train_df[list(continuous_cols)].to_numpy(dtype=np.float32)
        )
        val_df[list(continuous_cols)] = x_scaler.transform(
            val_df[list(continuous_cols)].to_numpy(dtype=np.float32)
        )
        test_df[list(continuous_cols)] = x_scaler.transform(
            test_df[list(continuous_cols)].to_numpy(dtype=np.float32)
        )

    y_scaler = StandardScaler()
    train_df[[TARGET_SCALED_COL]] = y_scaler.fit_transform(
        train_df[[TARGET_VALUE_COL]].to_numpy(dtype=np.float32)
    )
    val_df[[TARGET_SCALED_COL]] = y_scaler.transform(
        val_df[[TARGET_VALUE_COL]].to_numpy(dtype=np.float32)
    )
    test_df[[TARGET_SCALED_COL]] = y_scaler.transform(
        test_df[[TARGET_VALUE_COL]].to_numpy(dtype=np.float32)
    )

    for name, df in [("train", train_df), ("valid", val_df), ("test", test_df)]:
        if not np.isfinite(df[list(feature_cols)].to_numpy(dtype=np.float32)).all():
            raise ValueError(f"{name}: non-finite features after scaling.")
        if not np.isfinite(df[TARGET_SCALED_COL].to_numpy(dtype=np.float32)).all():
            raise ValueError(f"{name}: non-finite target after scaling.")

    return train_df, val_df, test_df, x_scaler, y_scaler


