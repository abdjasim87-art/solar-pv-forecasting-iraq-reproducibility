class SolarPVPerKwpDataset(Dataset):
    def __init__(
        self,
        df: pd.DataFrame,
        feature_cols: Sequence[str],
        lookback: int,
        horizon: int,
        use_city_embedding: bool,
    ):
        self.feature_cols = list(feature_cols)
        self.lookback = int(lookback)
        self.horizon = int(horizon)
        self.use_city_embedding = bool(use_city_embedding)

        self.x_by_city: List[np.ndarray] = []
        self.y_scaled_by_city: List[np.ndarray] = []
        self.y_raw_by_city: List[np.ndarray] = []
        self.daylight_by_city: List[np.ndarray] = []
        self.city_id_by_city: List[int] = []
        self.index_map: List[Tuple[int, int]] = []

        for _, g in df.groupby(CITY_COL, sort=False):
            g = g.sort_values(TIME_COL).reset_index(drop=True)

            x = np.ascontiguousarray(g[self.feature_cols].to_numpy(dtype=np.float32)).copy()
            y_scaled = np.ascontiguousarray(g[TARGET_SCALED_COL].to_numpy(dtype=np.float32)).copy()
            y_raw = np.ascontiguousarray(g[TARGET_VALUE_COL].to_numpy(dtype=np.float32)).copy()
            daylight = np.ascontiguousarray(g[DAYLIGHT_COL].to_numpy(dtype=np.float32)).copy()
            city_id = int(g["city_id"].iloc[0])

            city_idx = len(self.x_by_city)
            self.x_by_city.append(x)
            self.y_scaled_by_city.append(y_scaled)
            self.y_raw_by_city.append(y_raw)
            self.daylight_by_city.append(daylight)
            self.city_id_by_city.append(city_id)

            n = len(g)
            for t in range(self.lookback, n - self.horizon + 1):
                self.index_map.append((city_idx, t))

    def __len__(self) -> int:
        return len(self.index_map)

    def __getitem__(self, idx: int):
        city_idx, t = self.index_map[idx]

        x = self.x_by_city[city_idx][t - self.lookback: t].copy()
        y_scaled = self.y_scaled_by_city[city_idx][t: t + self.horizon].copy()
        y_raw = self.y_raw_by_city[city_idx][t: t + self.horizon].copy()
        daylight = self.daylight_by_city[city_idx][t: t + self.horizon].copy()
        city_id = self.city_id_by_city[city_idx]

        if self.use_city_embedding:
            return (
                torch.from_numpy(x),
                torch.tensor(city_id, dtype=torch.long),
                torch.from_numpy(y_scaled),
                torch.from_numpy(y_raw),
                torch.from_numpy(daylight),
            )

        return (
            torch.from_numpy(x),
            torch.from_numpy(y_scaled),
            torch.from_numpy(y_raw),
            torch.from_numpy(daylight),
        )


def unpack_batch(batch, use_city_embedding: bool):
    if use_city_embedding:
        x, city_id, y_scaled, y_raw, daylight = batch
        return x, city_id, y_scaled, y_raw, daylight
    x, y_scaled, y_raw, daylight = batch
    return x, None, y_scaled, y_raw, daylight


