def train_one_epoch(
    model,
    loader: DataLoader,
    optimizer,
    horizon_weights: torch.Tensor,
    device: str,
    use_city_embedding: bool,
    grad_clip: float,
    loss_name: str,
    huber_beta: float,
    daylight_weight: float,
    night_weight: float,
    production_weight: float,
    max_kw_per_kwp: float,
) -> float:
    model.train()
    loss_sum = 0.0
    count = 0

    for batch in loader:
        x, city_id, y_scaled, y_raw, daylight = unpack_batch(batch, use_city_embedding)

        x = x.to(device)
        y_scaled = y_scaled.to(device)
        y_raw = y_raw.to(device)
        daylight = daylight.to(device)

        if city_id is not None:
            city_id = city_id.to(device)

        optimizer.zero_grad(set_to_none=True)
        pred_scaled = model(x, city_id) if use_city_embedding else model(x)

        loss = solar_weighted_loss(
            pred_scaled=pred_scaled,
            true_scaled=y_scaled,
            true_raw=y_raw,
            daylight=daylight,
            horizon_weights=horizon_weights,
            loss_name=loss_name,
            huber_beta=huber_beta,
            daylight_weight=daylight_weight,
            night_weight=night_weight,
            production_weight=production_weight,
            max_kw_per_kwp=max_kw_per_kwp,
        )

        loss.backward()
        if grad_clip > 0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip)
        optimizer.step()

        batch_size = x.size(0)
        loss_sum += float(loss.item()) * batch_size
        count += batch_size

    return loss_sum / max(1, count)



@torch.no_grad()
def collect_predictions(
    model,
    loader: DataLoader,
    y_scaler: StandardScaler,
    device: str,
    use_city_embedding: bool,
    clip_per_kwp: bool,
    max_kw_per_kwp: float,
    force_night_zero: bool,
) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Return raw prediction arrays after the standard physical post-processing."""
    model.eval()

    pred_all = []
    true_all = []
    daylight_all = []

    for batch in loader:
        x, city_id, _, y_raw, daylight = unpack_batch(batch, use_city_embedding)

        x = x.to(device)
        if city_id is not None:
            city_id = city_id.to(device)

        pred_scaled = model(x, city_id) if use_city_embedding else model(x)
        pred_scaled_np = pred_scaled.detach().cpu().numpy()
        pred_raw = inverse_scaled(pred_scaled_np, y_scaler)

        daylight_np = daylight.numpy().astype(np.float32)
        pred_raw = final_physical_postprocess(
            pred_raw,
            daylight_np,
            clip_per_kwp=clip_per_kwp,
            max_kw_per_kwp=max_kw_per_kwp,
            force_night_zero=force_night_zero,
        )

        pred_all.append(pred_raw.astype(np.float32))
        true_all.append(y_raw.numpy().astype(np.float32))
        daylight_all.append(daylight_np.astype(np.float32))

    pred = np.concatenate(pred_all, axis=0)
    true = np.concatenate(true_all, axis=0)
    daylight = np.concatenate(daylight_all, axis=0)
    return pred, true, daylight


@torch.no_grad()
def evaluate_model(
    model,
    loader: DataLoader,
    y_scaler: StandardScaler,
    device: str,
    use_city_embedding: bool,
    reference_capacity_kwp: float,
    clip_per_kwp: bool,
    max_kw_per_kwp: float,
    force_night_zero: bool,
) -> Tuple[Dict[str, float], pd.DataFrame]:
    model.eval()

    pred_all = []
    true_all = []
    daylight_all = []

    for batch in loader:
        x, city_id, _, y_raw, daylight = unpack_batch(batch, use_city_embedding)

        x = x.to(device)
        if city_id is not None:
            city_id = city_id.to(device)

        pred_scaled = model(x, city_id) if use_city_embedding else model(x)
        pred_scaled_np = pred_scaled.detach().cpu().numpy()
        pred_raw = inverse_scaled(pred_scaled_np, y_scaler)

        daylight_np = daylight.numpy()
        if force_night_zero:
            pred_raw = np.where(daylight_np > 0.5, pred_raw, 0.0)

        if clip_per_kwp:
            pred_raw = np.clip(pred_raw, 0.0, float(max_kw_per_kwp))

        pred_all.append(pred_raw.astype(np.float32))
        true_all.append(y_raw.numpy().astype(np.float32))
        daylight_all.append(daylight_np.astype(np.float32))

    pred = np.concatenate(pred_all, axis=0)
    true = np.concatenate(true_all, axis=0)
    daylight = np.concatenate(daylight_all, axis=0)

    metrics = compute_all_metrics(pred, true, daylight, reference_capacity_kwp)
    ph = per_horizon_metrics(pred, true, daylight, reference_capacity_kwp)
    return metrics, ph


