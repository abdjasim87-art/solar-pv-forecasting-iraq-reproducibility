#!/usr/bin/env python3
"""
Solar LSTM PV-per-kWp forecasting model (v3)

Purpose
-------
Use the same train/valid/test CSV files used for the wind experiments, but train a
solar-only model. The model predicts reference PV AC power per installed kWp:

    target_solar_power_kw_per_kwp  (preferred)
    or pv_ac_power_kw_per_kwp      (fallback)

The final prediction can be scaled to any reference PV scenario:

    reference_power_kw = predicted_kw_per_kwp * reference_capacity_kwp

Default reference capacity is 3370 kWp to match the 3.37 MW wind reference turbine
scenario used in the wind path.

Important leakage policy
------------------------
The script excludes direct PV output/energy/reference/hybrid target columns from the
input features. Solar-history features are generated with shift(1), so they use only
past target values.

Default feature_set='basic' avoids using PV intermediate columns such as
pv_poa_global_wm2 and pv_cell_temperature_c. You can enable them with
--feature_set physics if your experiment is intended as a PV-model emulator or a
NASA-aligned scenario that allows those derived physical inputs.

v3 addition
-----------
After training, the script fits small post-processing calibration options on the
validation split only, then applies the best option to the test split. This is
intended to reduce systematic positive bias without changing the trained model.
Available corrections include global, daylight/night, horizon-wise, and
horizon-wise daylight/night bias corrections.
"""

