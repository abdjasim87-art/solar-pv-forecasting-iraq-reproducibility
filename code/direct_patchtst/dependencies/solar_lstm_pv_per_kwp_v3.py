def add_ar_solar_features(df: pd.DataFrame, target_col: str) -> pd.DataFrame:
    """Add lag/rolling/delta solar features, using only past values within each city."""
    df = df.copy()

    for _, g in df.groupby(CITY_COL, sort=True):
        idx = g.sort_values(TIME_COL).index
        y = df.loc[idx, target_col].astype(float)
        daylight = df.loc[idx, DAYLIGHT_COL].astype(float) if DAYLIGHT_COL in df.columns else (y > 0).astype(float)

        df.loc[idx, "solar_lag1"] = y.shift(1)
        df.loc[idx, "solar_lag2"] = y.shift(2)
        df.loc[idx, "solar_lag3"] = y.shift(3)
        df.loc[idx, "solar_lag6"] = y.shift(6)
        df.loc[idx, "solar_lag12"] = y.shift(12)
        df.loc[idx, "solar_lag24"] = y.shift(24)
        df.loc[idx, "solar_lag48"] = y.shift(48)
        df.loc[idx, "solar_lag168"] = y.shift(168)

        df.loc[idx, "solar_roll3_mean"] = y.shift(1).rolling(3, min_periods=1).mean()
        df.loc[idx, "solar_roll6_mean"] = y.shift(1).rolling(6, min_periods=1).mean()
        df.loc[idx, "solar_roll12_mean"] = y.shift(1).rolling(12, min_periods=1).mean()
        df.loc[idx, "solar_roll24_mean"] = y.shift(1).rolling(24, min_periods=1).mean()

        df.loc[idx, "solar_roll3_std"] = y.shift(1).rolling(3, min_periods=2).std().fillna(0.0)
        df.loc[idx, "solar_roll6_std"] = y.shift(1).rolling(6, min_periods=2).std().fillna(0.0)
        df.loc[idx, "solar_roll12_std"] = y.shift(1).rolling(12, min_periods=2).std().fillna(0.0)

        df.loc[idx, "solar_delta1"] = y.shift(1) - y.shift(2)
        df.loc[idx, "solar_delta2"] = y.shift(2) - y.shift(3)
        df.loc[idx, "solar_delta3"] = y.shift(3) - y.shift(4)

        df.loc[idx, "solar_daylight_lag1"] = daylight.shift(1)

    return df


