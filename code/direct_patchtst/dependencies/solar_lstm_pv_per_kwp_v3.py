class EarlyStopping:
    def __init__(self, patience: int, min_delta: float):
        self.patience = int(patience)
        self.min_delta = float(min_delta)
        self.best = float("inf")
        self.bad_epochs = 0

    def step(self, value: float) -> Tuple[bool, bool]:
        improved = (self.best - value) > self.min_delta
        if improved:
            self.best = value
            self.bad_epochs = 0
            return False, True
        self.bad_epochs += 1
        return self.bad_epochs >= self.patience, False


