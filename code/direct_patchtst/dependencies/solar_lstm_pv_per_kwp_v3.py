def load_split(path: str, split_name: str, target_col_arg: str) -> Tuple[pd.DataFrame, str]:
    df = pd.read_csv(path)

    if TIME_COL not in df.columns:
        raise ValueError(f"{split_name}: missing column {TIME_COL}")

    if CITY_COL not in df.columns:
        if RAW_CITY_COL in df.columns:
            df[CITY_COL] = df[RAW_CITY_COL].astype(str).str.strip()
        else:
            raise ValueError(f"{split_name}: missing column {CITY_COL}")

    target_col = resolve_target_col(df, target_col_arg)

    df[TIME_COL] = pd.to_datetime(df[TIME_COL], errors="coerce", utc=True)
    df[CITY_COL] = df[CITY_COL].astype(str).str.strip()
    df[target_col] = pd.to_numeric(df[target_col], errors="coerce")

    if DAYLIGHT_COL in df.columns:
        df[DAYLIGHT_COL] = pd.to_numeric(df[DAYLIGHT_COL], errors="coerce").fillna(0).astype(int)
    else:
        df[DAYLIGHT_COL] = (df[target_col].fillna(0) > 0).astype(int)

    df = df.dropna(subset=[TIME_COL, CITY_COL, target_col]).copy()

    if "city_id" not in df.columns:
        city_vocab = {city: idx for idx, city in enumerate(sorted(df[CITY_COL].unique()))}
        df["city_id"] = df[CITY_COL].map(city_vocab).astype(int)

    df = df.sort_values([CITY_COL, TIME_COL]).reset_index(drop=True)
    return df, target_col


def check_split_integrity(train_df: pd.DataFrame, val_df: pd.DataFrame, test_df: pd.DataFrame) -> None:
    train_cities = sorted(train_df[CITY_COL].unique().tolist())
    val_cities = sorted(val_df[CITY_COL].unique().tolist())
    test_cities = sorted(test_df[CITY_COL].unique().tolist())

    if not (train_cities == val_cities == test_cities):
        raise ValueError(
            f"City mismatch.\nTrain: {train_cities}\nValid: {val_cities}\nTest: {test_cities}"
        )

    for name, df in [("train", train_df), ("valid", val_df), ("test", test_df)]:
        dups = int(df.duplicated(subset=[CITY_COL, TIME_COL]).sum())
        if dups > 0:
            raise ValueError(f"{name}: {dups} duplicated city-time rows.")

    print("Split integrity check: PASSED")
    print(f"Cities : {train_cities}")
    print(f"Rows   : train={len(train_df):,}  valid={len(val_df):,}  test={len(test_df):,}")


def prepare_physical_target(df: pd.DataFrame, target_col: str) -> pd.DataFrame:
    df = df.copy()
    df[RAW_TARGET_COL] = pd.to_numeric(df[target_col], errors="coerce")
