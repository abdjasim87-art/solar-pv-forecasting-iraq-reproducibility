def available_only(cols: Sequence[str], available_cols: Sequence[str]) -> List[str]:
    available = set(available_cols)
    return [c for c in cols if c in available]


def float_tag(value: float) -> str:
    """Make a filesystem-safe compact tag for float hyperparameters."""
    text = f"{float(value):g}"
    return text.replace("-", "m").replace(".", "p")


def is_no_scale_column(col: str) -> bool:
    if col in BINARY_COLS:
        return True
    if "_sin" in col or "_cos" in col:
        return True
    if col == "city_id":
        return True
    return False


def resolve_target_col(df: pd.DataFrame, requested: str) -> str:
    requested = requested.strip()
    if requested.lower() != "auto":
        if requested not in df.columns:
            raise ValueError(f"Requested target column not found: {requested}")
        return requested

    if PREFERRED_TARGET_COL in df.columns:
        return PREFERRED_TARGET_COL
    if FALLBACK_TARGET_COL in df.columns:
        return FALLBACK_TARGET_COL
    raise ValueError(
        f"No solar target found. Expected {PREFERRED_TARGET_COL!r} or {FALLBACK_TARGET_COL!r}."
    )


def build_feature_columns(
    df: pd.DataFrame,
    feature_set: str,
    use_solar_history: bool,
) -> Tuple[List[str], List[str]]:
    feature_set = feature_set.lower().strip()

    candidates = (
        TIME_FEATURES
        + WEATHER_RADIATION_FEATURES
        + SOLAR_GEOMETRY_FEATURES
        + STATIC_LOCATION_FEATURES
    )

    if use_solar_history:
        candidates += SOLAR_AR_FEATURES

    if feature_set == "basic":
        pass
    elif feature_set == "physics":
        candidates += PV_PHYSICS_FEATURES
    else:
        raise ValueError("feature_set must be 'basic' or 'physics'.")

    feature_cols = available_only(candidates, df.columns)
    feature_cols = list(dict.fromkeys(feature_cols))

    feature_cols = [
        c for c in feature_cols
        if c not in METADATA_COLS and c not in LEAKAGE_OR_NON_SOLAR_FEATURES
    ]

    if not feature_cols:
        raise ValueError("No feature columns selected.")

    non_numeric = [c for c in feature_cols if not pd.api.types.is_numeric_dtype(df[c])]
    if non_numeric:
        raise ValueError(f"Non-numeric features selected: {non_numeric}")

    continuous_cols = [c for c in feature_cols if not is_no_scale_column(c)]
    return feature_cols, continuous_cols


