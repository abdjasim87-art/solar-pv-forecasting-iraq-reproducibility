class SolarLSTM(nn.Module):
    def __init__(
        self,
        n_features: int,
        hidden_size: int,
        num_layers: int,
        dropout: float,
        horizon: int,
        head_hidden: int,
    ):
        super().__init__()
        self.lstm = nn.LSTM(
            input_size=n_features,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        self.head = nn.Sequential(
            nn.Linear(hidden_size, head_hidden),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(head_hidden, max(1, head_hidden // 2)),
            nn.ReLU(),
            nn.Dropout(dropout * 0.5),
            nn.Linear(max(1, head_hidden // 2), horizon),
        )

    def forward(self, x: torch.Tensor, city_id=None) -> torch.Tensor:
        out, _ = self.lstm(x)
        last = out[:, -1, :]
        return self.head(last)


class SolarLSTMCityEmbedding(nn.Module):
    def __init__(
        self,
        n_features: int,
        n_cities: int,
        city_embedding_dim: int,
        hidden_size: int,
        num_layers: int,
        dropout: float,
        horizon: int,
        head_hidden: int,
    ):
        super().__init__()
        self.embedding = nn.Embedding(n_cities, city_embedding_dim)
        self.lstm = nn.LSTM(
            input_size=n_features,
            hidden_size=hidden_size,
            num_layers=num_layers,
            batch_first=True,
            dropout=dropout if num_layers > 1 else 0.0,
        )
        self.head = nn.Sequential(
            nn.Linear(hidden_size + city_embedding_dim, head_hidden),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Linear(head_hidden, max(1, head_hidden // 2)),
            nn.ReLU(),
            nn.Dropout(dropout * 0.5),
            nn.Linear(max(1, head_hidden // 2), horizon),
        )

    def forward(self, x: torch.Tensor, city_id: torch.Tensor) -> torch.Tensor:
        out, _ = self.lstm(x)
        last = out[:, -1, :]
        emb = self.embedding(city_id)
        z = torch.cat([last, emb], dim=1)
        return self.head(z)


